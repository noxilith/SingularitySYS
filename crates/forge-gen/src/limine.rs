use crate::meta::{BootInfo, Meta, with_root_subvol};

/// What every entry loads or shows beyond the kernel: extra initrds (CPU microcode, first) and the wallpaper.
#[derive(Debug, Default, Clone)]
pub struct Extras {
    pub early: Vec<String>,
    /// A file name in the boot directory.
    pub wallpaper: Option<String>,
    /// BLAKE2b-512 (hex) of boot files by name. With Secure Boot the loader only reads files it has a hash for, so every
    /// path that has one here gets it appended (`boot():/vmlinuz#hash`).
    pub pins: std::collections::BTreeMap<String, String>,
}

/// `boot():/name`, with `#hash` when the file is pinned.
fn path(name: &str, pins: &std::collections::BTreeMap<String, String>) -> String {
    match pins.get(name) {
        Some(h) => format!("boot():/{name}#{h}"),
        None => format!("boot():/{name}"),
    }
}

fn entry(out: &mut String, depth: usize, name: &str, comment: &str, boot: &BootInfo, subvol: &str, ro: bool, early: &[String], pins: &std::collections::BTreeMap<String, String>) {
    let slashes = "/".repeat(depth);
    let pad = "    ".repeat(depth - 1);
    out.push_str(&format!("{slashes}{name}\n"));
    out.push_str(&format!("{pad}    comment: {comment}\n"));
    out.push_str(&format!("{pad}    protocol: linux\n"));
    out.push_str(&format!("{pad}    path: {}\n", path(&boot.kernel, pins)));
    out.push_str(&format!(
        "{pad}    cmdline: {}\n",
        with_root_subvol(&boot.cmdline, subvol, ro)
    ));
    // Early initrds (CPU microcode) come first: the kernel looks for microcode in the first ones.
    for m in early {
        out.push_str(&format!("{pad}    module_path: {}\n", path(m, pins)));
    }
    if !boot.initramfs.is_empty() {
        out.push_str(&format!("{pad}    module_path: {}\n", path(&boot.initramfs, pins)));
    }
}

fn label(text: &str) -> String {
    let clean: String = text.chars().filter(|c| !c.is_control()).collect();
    clean.chars().take(60).collect()
}

/// Render `limine.conf`: the live entry first, then a Generations submenu
/// (newest first) in which every generation boots its own kernel and command
/// line, read-only, from its own snapshot.
pub fn render(live: &BootInfo, live_subvol: &str, gens: &[Meta], extras: &Extras) -> String {
    let early = &extras.early;
    let wallpaper = extras.wallpaper.as_ref().map(|w| path(w, &extras.pins));
    let mut out = String::from(
        "# managed by forge: regenerated by `forge gen rewrite-limine`; do not edit\n\
         timeout: 5\n",
    );
    out.push_str(&crate::theme::limine_theme(wallpaper.as_deref()));
    out.push('\n');
    entry(&mut out, 1, "Singularity", "Start the system as it is now", live, live_subvol, false, early, &extras.pins);
    if !gens.is_empty() {
        out.push_str("\n/Generations\n");
        let mut sorted: Vec<&Meta> = gens.iter().collect();
        sorted.sort_by_key(|m| std::cmp::Reverse(m.id));
        for m in sorted {
            let name = format!("Generation {}: {}", m.id, label(&m.description));
            let subvol = format!("@snapshots/gen-{}", m.id);
            entry(&mut out, 2, &name, "Roll back: boot this earlier state of the system (read-only; make it permanent with forge gen rollback)", &m.boot(), &subvol, true, early, &extras.pins);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_menu_is_themed_and_every_entry_says_what_it_does() {
        let c = render(&boot("6.3"), "@", &[meta(1, "6.1", "first")], &Extras { early: vec![], wallpaper: Some("wallpaper.jpg".into()), ..Default::default() });
        assert!(c.contains("interface_branding: SingularitySYS") && c.contains("wallpaper: boot():/wallpaper.jpg"), "{c}");
        assert_eq!(c.matches("comment: ").count(), 2, "one for the live entry and one for the generation: {c}");
        // Options come before the first entry.
        assert!(c.find("wallpaper:").unwrap() < c.find("/Singularity").unwrap());
    }

    #[test]
    fn every_entry_loads_the_microcode_image_before_the_initramfs() {
        let early = vec!["microcode.img".to_string()];
        let c = render(&boot("6.3"), "@", &[meta(1, "6.1", "first")], &Extras { early, wallpaper: None, ..Default::default() });
        assert_eq!(c.matches("module_path: boot():/microcode.img").count(), 2, "the live entry and the generation: {c}");
        let first = c.find("microcode.img").unwrap();
        let initramfs = c.find("initramfs-6.3.img").unwrap();
        assert!(first < initramfs, "microcode first: {c}");
        assert!(!render(&boot("6.3"), "@", &[], &Extras::default()).contains("microcode"));
    }

    #[test]
    fn with_secure_boot_every_file_the_loader_reads_carries_its_hash() {
        let mut pins = std::collections::BTreeMap::new();
        for (n, h) in [("vmlinuz-6.3", "aa"), ("initramfs-6.3.img", "bb"), ("microcode.img", "cc"), ("wallpaper.jpg", "dd"), ("vmlinuz-6.1", "ee")] {
            pins.insert(n.to_string(), h.repeat(64));
        }
        let extras = Extras { early: vec!["microcode.img".into()], wallpaper: Some("wallpaper.jpg".into()), pins };
        let mut old = boot("6.1");
        old.initramfs.clear();
        let c = render(&boot("6.3"), "@", &[meta(1, "6.1", "first")], &extras);
        for want in ["path: boot():/vmlinuz-6.3#aaaa", "module_path: boot():/initramfs-6.3.img#bbbb", "module_path: boot():/microcode.img#cccc", "wallpaper: boot():/wallpaper.jpg#dddd", "path: boot():/vmlinuz-6.1#eeee"] {
            assert!(c.contains(want), "{want}\n{c}");
        }
        assert!(!render(&boot("6.3"), "@", &[], &Extras::default()).contains("vmlinuz-6.3#"), "no hashes without Secure Boot");
    }

    fn boot(k: &str) -> BootInfo {
        BootInfo { kernel: format!("vmlinuz-{k}"), initramfs: format!("initramfs-{k}.img"), cmdline: "root=UUID=abc".into() }
    }

    fn meta(id: u32, k: &str, desc: &str) -> Meta {
        let b = boot(k);
        Meta { id, description: desc.into(), created: 0, kernel: b.kernel, initramfs: b.initramfs, cmdline: b.cmdline, store_paths: vec![] }
    }

    #[test]
    fn entries_without_an_initramfs_have_no_module_path() {
        let mut b = boot("6.3");
        b.initramfs.clear();
        assert!(b.validate().is_ok(), "an empty initramfs name means none");
        let mut m = meta(1, "6.1", "first");
        m.initramfs.clear();
        let c = render(&b, "@", &[m], &Extras::default());
        assert!(!c.contains("module_path"), "{c}");
        assert!(c.contains("path: boot():/vmlinuz-6.3"));
        assert!(c.contains("//Generation 1: first"));
    }

    #[test]
    fn live_entry_only_when_no_generations() {
        let c = render(&boot("6.2"), "@", &[], &Extras::default());
        assert!(c.contains("/Singularity\n"));
        assert!(c.contains("cmdline: root=UUID=abc rootflags=subvol=@ rw"));
        assert!(!c.contains("Generations"));
    }

    #[test]
    fn each_generation_pins_its_own_kernel_and_subvolume() {
        let c = render(&boot("6.3"), "@", &[meta(1, "6.1", "first"), meta(2, "6.2", "second")], &Extras::default());
        assert!(c.contains("path: boot():/vmlinuz-6.3"), "live entry uses the current kernel");
        assert!(c.contains("//Generation 1: first"));
        assert!(c.contains("path: boot():/vmlinuz-6.1"));
        assert!(c.contains("rootflags=subvol=@snapshots/gen-1 ro"));
        assert!(c.contains("rootflags=subvol=@snapshots/gen-2 ro"));
        assert!(c.find("Generation 2").unwrap() < c.find("Generation 1").unwrap(), "newest first");
    }

    #[test]
    fn staged_rollback_boots_the_next_subvolume() {
        assert!(render(&boot("6.2"), "@.next", &[], &Extras::default()).contains("rootflags=subvol=@.next rw"));
    }

    #[test]
    fn description_cannot_inject_entries() {
        let c = render(&boot("6.2"), "@", &[meta(1, "6.2", "x\n/Evil\n    cmdline: bad")], &Extras::default());
        assert!(!c.contains("\n/Evil"));
    }
}
